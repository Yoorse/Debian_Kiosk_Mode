#!/usr/bin/env bash
#
# kiosk-xorg-setup.sh
# Switch a Debian kiosk from Wayland/Squeekboard to:
#   tty1 autologin -> startx -> Openbox + Onboard (auto-show) + Chromium
#
# Chromium runs as a normal maximized window (not --kiosk) with two sites
# opened as pinned tabs. A small local extension keeps them pinned.
#
# Onboard sends real key presses (XTest), so keyup-based web filters work.
#
# Usage (as root):
#   sudo ./kiosk-xorg-setup.sh -u kiosk -1 "http://mes-server/mes/" -2 "http://other-site/"
#
# Or via environment variables:
#   sudo KIOSK_USER=kiosk PIN_URL1="http://mes-server/mes/" PIN_URL2="http://other-site/" ./kiosk-xorg-setup.sh
#
# Undo: see /root/kiosk-disabled-services.txt for services to re-enable,
#       remove /etc/systemd/system/getty@tty1.service.d/autologin.conf,
#       and run: systemctl set-default graphical.target

set -euo pipefail

KIOSK_USER="${KIOSK_USER:-kiosk}"
PIN_URL1="${PIN_URL1:-http://your-mes-server/mes/}"
PIN_URL2="${PIN_URL2:-http://your-second-site/}"
EXT_DIR="/opt/kiosk-pin-tabs"

usage() {
    echo "Usage: $0 [-u kiosk_user] [-1 first_pinned_url] [-2 second_pinned_url]"
    exit 1
}

while getopts "u:1:2:h" opt; do
    case "$opt" in
        u) KIOSK_USER="$OPTARG" ;;
        1) PIN_URL1="$OPTARG" ;;
        2) PIN_URL2="$OPTARG" ;;
        *) usage ;;
    esac
done

log() { echo -e "\e[1;32m==>\e[0m $*"; }
warn() { echo -e "\e[1;33m!!\e[0m $*"; }

# --- Sanity checks ----------------------------------------------------------
if [ "$(id -u)" -ne 0 ]; then
    echo "Run this script as root (sudo)." >&2
    exit 1
fi

if ! id "$KIOSK_USER" >/dev/null 2>&1; then
    echo "User '$KIOSK_USER' does not exist. Create it first or use -u." >&2
    exit 1
fi

HOME_DIR="$(getent passwd "$KIOSK_USER" | cut -d: -f6)"
STAMP="$(date +%Y%m%d-%H%M%S)"

log "Kiosk user   : $KIOSK_USER ($HOME_DIR)"
log "Pinned tab 1 : $PIN_URL1"
log "Pinned tab 2 : $PIN_URL2"

# --- Packages ---------------------------------------------------------------
log "Installing Xorg, Openbox, Onboard and helpers..."
export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y \
    xserver-xorg xinit xserver-xorg-input-libinput x11-xserver-utils \
    openbox onboard at-spi2-core dbus-x11 unclutter \
    gsettings-desktop-schemas dconf-cli dconf-gsettings-backend

if ! command -v chromium >/dev/null 2>&1 && ! command -v chromium-browser >/dev/null 2>&1; then
    log "Installing Chromium..."
    apt-get install -y chromium
fi
CHROMIUM_BIN="$(command -v chromium || command -v chromium-browser)"
log "Chromium     : $CHROMIUM_BIN"

# --- Backup helper ----------------------------------------------------------
backup() {
    if [ -f "$1" ]; then
        cp -a "$1" "$1.bak-$STAMP"
        warn "Backed up $1 -> $1.bak-$STAMP"
    fi
}

# --- Pin-tabs extension -----------------------------------------------------
# Chromium has no command-line flag for pinned tabs, so this tiny local
# extension pins any tab whose URL starts with one of the two URLs, and
# reopens a pinned tab at startup if it is missing.
log "Writing pin-tabs extension to $EXT_DIR..."
mkdir -p "$EXT_DIR"

cat > "$EXT_DIR/manifest.json" <<'EOF'
{
  "manifest_version": 3,
  "name": "Kiosk pinned tabs",
  "version": "1.0",
  "description": "Keeps the configured kiosk sites open as pinned tabs.",
  "permissions": ["tabs"],
  "background": { "service_worker": "background.js" }
}
EOF

# JSON-escape the URLs for safe embedding in JavaScript
js_str() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }

cat > "$EXT_DIR/background.js" <<EOF
// Generated by kiosk-xorg-setup.sh on $STAMP
const PINNED = [
  "$(js_str "$PIN_URL1")",
  "$(js_str "$PIN_URL2")"
];

const urlOf = t => t.pendingUrl || t.url || "";
const isPinnedSite = u => PINNED.some(p => u.startsWith(p));

async function pinMatching() {
  const tabs = await chrome.tabs.query({});
  for (const t of tabs) {
    if (!t.pinned && isPinnedSite(urlOf(t))) {
      await chrome.tabs.update(t.id, { pinned: true });
    }
  }
}

async function ensureOpen() {
  const tabs = await chrome.tabs.query({});
  // Create pinned tabs in order, so tab 1 ends up left of tab 2
  for (let i = 0; i < PINNED.length; i++) {
    const p = PINNED[i];
    const existing = tabs.find(t => urlOf(t).startsWith(p));
    if (existing) {
      await chrome.tabs.update(existing.id, { pinned: true });
      await chrome.tabs.move(existing.id, { index: i });
    } else {
      await chrome.tabs.create({ url: p, pinned: true, index: i, active: i === 0 });
    }
  }
  // Close the leftover empty New Tab page, if any
  const after = await chrome.tabs.query({});
  for (const t of after) {
    const u = urlOf(t);
    if (!t.pinned && (u === "chrome://newtab/" || u === "chrome://new-tab-page/")) {
      await chrome.tabs.remove(t.id);
    }
  }
  const [first] = await chrome.tabs.query({ pinned: true, index: 0 });
  if (first) await chrome.tabs.update(first.id, { active: true });
}

// Give Chromium a moment to restore/open its initial tabs before checking
const startup = () => setTimeout(() => ensureOpen().catch(console.error), 1500);
chrome.runtime.onStartup.addListener(startup);
chrome.runtime.onInstalled.addListener(startup);

// Pin a matching tab as soon as it navigates to one of the sites
chrome.tabs.onUpdated.addListener((id, info, tab) => {
  if (info.url || info.status === "complete") pinMatching().catch(console.error);
});
EOF

chmod -R a+rX "$EXT_DIR"

# --- Onboard + accessibility settings (system-wide, locked) -----------------
# Applied as dconf system defaults with locks, so they take effect no matter
# what Onboard saved for the user before (e.g. a floating window).
log "Configuring Onboard: hidden until a text field is focused, docked at bottom..."
mkdir -p /etc/dconf/profile /etc/dconf/db/local.d/locks

if [ -f /etc/dconf/profile/user ]; then
    backup /etc/dconf/profile/user
    grep -q '^user-db:user' /etc/dconf/profile/user || sed -i '1i user-db:user' /etc/dconf/profile/user
    grep -q '^system-db:local' /etc/dconf/profile/user || echo 'system-db:local' >> /etc/dconf/profile/user
else
    printf 'user-db:user\nsystem-db:local\n' > /etc/dconf/profile/user
fi

cat > /etc/dconf/db/local.d/00-kiosk-onboard <<'EOF'
# Generated by kiosk-xorg-setup.sh
[org/gnome/desktop/interface]
toolkit-accessibility=true

[org/onboard]
start-minimized=true
show-status-icon=false

[org/onboard/auto-show]
enabled=true
keyboard-device-detection-enabled=false

[org/onboard/window]
docking-enabled=true
docking-edge='bottom'
force-to-top=true

[org/onboard/icon-palette]
in-use=false
EOF

cat > /etc/dconf/db/local.d/locks/00-kiosk-onboard <<'EOF'
/org/gnome/desktop/interface/toolkit-accessibility
/org/onboard/start-minimized
/org/onboard/show-status-icon
/org/onboard/auto-show/enabled
/org/onboard/auto-show/keyboard-device-detection-enabled
/org/onboard/window/docking-enabled
/org/onboard/window/docking-edge
/org/onboard/window/force-to-top
/org/onboard/icon-palette/in-use
EOF

dconf update

# --- ~/.xinitrc -------------------------------------------------------------
log "Writing $HOME_DIR/.xinitrc..."
backup "$HOME_DIR/.xinitrc"
cat > "$HOME_DIR/.xinitrc" <<EOF
#!/bin/sh
# Generated by kiosk-xorg-setup.sh on $STAMP

CHROMIUM="$CHROMIUM_BIN"
PIN_EXT="$EXT_DIR"

# Make sure there is a D-Bus session (needed for gsettings and accessibility)
if [ -z "\$DBUS_SESSION_BUS_ADDRESS" ]; then
    eval "\$(dbus-launch --sh-syntax --exit-with-session)"
fi

# No screen blanking / power saving
xset s off
xset -dpms
xset s noblank

# Hide mouse pointer when idle
unclutter -idle 1 &

# Window manager
openbox &

# Accessibility bus, so Onboard can see when a text field in Chromium gets focus
export ACCESSIBILITY_ENABLED=1
export NO_AT_BRIDGE=0
for l in /usr/libexec/at-spi-bus-launcher /usr/lib/at-spi2-core/at-spi-bus-launcher; do
    if [ -x "\$l" ]; then "\$l" --launch-immediately & break; fi
done
sleep 1

# Onboard settings come from /etc/dconf/db/local.d/00-kiosk-onboard:
# hidden at start, pops up docked at the bottom when a text field is focused.
onboard > "\$HOME/.onboard.log" 2>&1 &

# Chromium, restarted automatically if it closes or crashes.
# The pin-tabs extension opens the two sites as pinned tabs.
PREFS="\$HOME/.config/chromium/Default/Preferences"
while true; do
    # Suppress the "Chromium didn't shut down correctly" bubble
    if [ -f "\$PREFS" ]; then
        sed -i 's/"exited_cleanly":false/"exited_cleanly":true/; s/"exit_type":"[^"]*"/"exit_type":"Normal"/' "\$PREFS"
    fi

    "\$CHROMIUM" \\
        --start-maximized \\
        --ozone-platform=x11 \\
        --force-renderer-accessibility \\
        --load-extension="\$PIN_EXT" \\
        --disable-features=DisableLoadExtensionCommandLineSwitch \\
        --noerrdialogs \\
        --disable-infobars \\
        --disable-session-crashed-bubble \\
        --no-first-run \\
        --check-for-update-interval=31536000

    sleep 2
done
EOF
chmod 755 "$HOME_DIR/.xinitrc"
chown "$KIOSK_USER": "$HOME_DIR/.xinitrc"

# --- ~/.bash_profile: start X on tty1 ---------------------------------------
log "Configuring startx on tty1 in $HOME_DIR/.bash_profile..."
MARKER="# kiosk-xorg-setup: start X on tty1"
touch "$HOME_DIR/.bash_profile"
if ! grep -qF "$MARKER" "$HOME_DIR/.bash_profile"; then
    backup "$HOME_DIR/.bash_profile"
    cat >> "$HOME_DIR/.bash_profile" <<'EOF'

# kiosk-xorg-setup: start X on tty1
if [ -z "$DISPLAY" ] && [ "$(tty)" = /dev/tty1 ]; then
    exec startx
fi
EOF
fi
chown "$KIOSK_USER": "$HOME_DIR/.bash_profile"

# --- Autologin on tty1 ------------------------------------------------------
log "Enabling autologin for $KIOSK_USER on tty1..."
mkdir -p /etc/systemd/system/getty@tty1.service.d
cat > /etc/systemd/system/getty@tty1.service.d/autologin.conf <<EOF
[Service]
ExecStart=
ExecStart=-/sbin/agetty --autologin $KIOSK_USER --noclear %I \$TERM
EOF

# Allow any user to start X (needed when started from a console login)
if [ -f /etc/X11/Xwrapper.config ]; then
    backup /etc/X11/Xwrapper.config
    sed -i 's/^allowed_users=.*/allowed_users=anybody/' /etc/X11/Xwrapper.config
    grep -q '^allowed_users=' /etc/X11/Xwrapper.config || echo 'allowed_users=anybody' >> /etc/X11/Xwrapper.config
else
    echo 'allowed_users=anybody' > /etc/X11/Xwrapper.config
fi

# --- Disable the old Wayland / display-manager session ----------------------
log "Disabling existing display managers / Wayland sessions..."
DISABLED_LOG=/root/kiosk-disabled-services.txt
for svc in gdm3 gdm sddm lightdm greetd phosh cage@tty1 seatd-launch; do
    if systemctl is-enabled "$svc" >/dev/null 2>&1; then
        systemctl disable "$svc"
        echo "$svc" >> "$DISABLED_LOG"
        warn "Disabled $svc (logged in $DISABLED_LOG)"
    fi
done

systemctl set-default multi-user.target
systemctl daemon-reload

# --- Done -------------------------------------------------------------------
log "Done."
echo
echo "  Reboot to start the Xorg kiosk:  sudo reboot"
echo
echo "  Pinned tabs match by URL prefix. If a site redirects to a different"
echo "  address (e.g. http -> https, or a login page on another host), use"
echo "  the address it ends up on, or edit PINNED in $EXT_DIR/background.js."
echo
echo "  If your old kiosk was started some other way (autostart entry,"
echo "  custom systemd unit, ~/.bash_profile line), disable that too."
echo
echo "  Touch lands in the wrong place? Add to ~/.xinitrc before 'openbox &':"
echo "    xinput map-to-output \"<touch device name>\" <output>"
echo "  (see: DISPLAY=:0 xinput list   and   DISPLAY=:0 xrandr)"
